const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const vm = require('node:vm');
const source = fs.readFileSync('src/utils/commerce.ts', 'utf8');
const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const context = { exports: {} };
vm.runInNewContext(code, context);
const { checkoutTotals } = context.exports;
assert.equal(checkoutTotals(249, 10).total, 224.1);
assert.equal(checkoutTotals(38, 20).total, 42.4);
assert.equal(checkoutTotals(149.99).shipping, 12);
assert.equal(checkoutTotals(150).shipping, 0);
assert.equal(checkoutTotals(150, 10).shipping, 0);
assert.equal(checkoutTotals(32.99, 10).discount, 3.3);
assert.equal(checkoutTotals(32.99, 10).total, 41.69);
assert.equal(checkoutTotals(0, 0, false).total, 0);
assert.equal(checkoutTotals(100, -10).discount, 0);
assert.equal(checkoutTotals(100, 100).discount, 90);
console.log('10 commerce checks passed: discounts, shipping threshold, empty cart, and cent rounding.');
